//! Templates, compiled into the binary. Autoescaping is on for `*.html`.

use minijinja::{Environment, Value};

use super::{format, icons};
use crate::{ids, stats};

pub type Views = Environment<'static>;

const TEMPLATES: &[(&str, &str)] = &[
    ("layout.html", include_str!("../../templates/layout.html")),
    ("index.html", include_str!("../../templates/index.html")),
    ("details.html", include_str!("../../templates/details.html")),
    (
        "dashboard.html",
        include_str!("../../templates/dashboard.html"),
    ),
    ("share.html", include_str!("../../templates/share.html")),
    ("stats.html", include_str!("../../templates/stats.html")),
    (
        "analysis.html",
        include_str!("../../templates/analysis.html"),
    ),
];

pub fn build_views() -> Views {
    let mut env = Environment::new();
    for (name, source) in TEMPLATES {
        env.add_template(name, source)
            .unwrap_or_else(|e| panic!("template {name}: {e:#}"));
    }
    env.add_filter("crashid", |id: String| ids::display(&id));
    env.add_filter("utc", format::utc);
    env.add_filter("ago", |ts: i64| format::reldate(ts, stats::now()));
    env.add_filter("bytes", format::human_bytes);
    // Generated by us from fixed data or a hash, never from user input, so safe to print as is.
    env.add_function("icon", |name: &str| {
        Value::from_safe_string(icons::icon(name))
    });
    env.add_filter("identicon", |seed: &str| {
        Value::from_safe_string(icons::identicon(seed))
    });
    env
}
